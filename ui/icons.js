/** Each lit pixel as a 1×1 square; runs along a row are merged into one rectangle. */
function pathFor(rows) {
  let d = "";
  rows.forEach((row, y) => {
    for (const m of row.matchAll(/#+/g)) d += `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`;
  });
  return d;
}

export function icon(name) {
  const svg = s("svg", { class: "icon", viewBox: "0 0 16 16", width: 16, height: 16, "aria-hidden": "true", "shape-rendering": "crispEdges" });
  svg.append(s("path", { d: pathFor(GRIDS[name]) }));
  return svg;
}
